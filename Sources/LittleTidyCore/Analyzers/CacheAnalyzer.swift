import Foundation

public struct CacheCandidate: Codable, Sendable {
    public let url: URL
    public let displayName: String
    public let sizeBytes: Int64
    public let lastModified: Date?
    public let reason: String
    public let confidence: Confidence

    public init(
        url: URL,
        displayName: String,
        sizeBytes: Int64,
        lastModified: Date?,
        reason: String,
        confidence: Confidence
    ) {
        self.url = url
        self.displayName = displayName
        self.sizeBytes = sizeBytes
        self.lastModified = lastModified
        self.reason = reason
        self.confidence = confidence
    }
}

/// Finds regenerable cache directories, framework caches, logs, and verified
/// per-project build folders that are safe to move to the Trash.
///
/// Everything reported here is recreated automatically by the owning app or
/// tool, and removal stays Trash-only by default so it is always reversible.
public struct CacheAnalyzer {
    private let fileManager: FileManager
    private let home: URL
    private let darwinUserCacheDirectory: URL?

    public init(
        fileManager: FileManager = .default,
        homeDirectory: URL? = nil,
        darwinUserCacheDirectory: URL? = nil
    ) {
        self.fileManager = fileManager
        self.home = (homeDirectory ?? fileManager.homeDirectoryForCurrentUser).resolvingSymlinksInPath()
        self.darwinUserCacheDirectory = darwinUserCacheDirectory?.resolvingSymlinksInPath()
    }

    private struct PendingCandidate {
        let url: URL
        let displayName: String
        let reason: String
        let confidence: Confidence
    }

    public func findCaches(
        minimumSize: Int64 = 1_000_000,
        scanRoots: [URL] = []
    ) throws -> [CacheCandidate] {
        var pending: [PendingCandidate] = []
        var seenCanonicalPaths: Set<String> = []

        func enqueue(
            url: URL,
            displayName: String,
            reason: String,
            confidence: Confidence = .high
        ) {
            guard isEligibleCacheDirectory(url) else { return }
            let canonical = url.standardizedFileURL.path
            guard seenCanonicalPaths.insert(canonical).inserted else { return }
            pending.append(PendingCandidate(
                url: url,
                displayName: displayName,
                reason: reason,
                confidence: confidence
            ))
        }

        // 1. Xcode DerivedData — presented as an aggregate item in General Caches.
        let derivedData = home.appendingPathComponent("Library/Developer/Xcode/DerivedData", isDirectory: true)
        enqueue(
            url: derivedData,
            displayName: "Xcode DerivedData",
            reason: "Xcode build intermediates and indexes. Rebuilt automatically on the next build."
        )

        // 2. Hierarchy 1: Per-app user caches (~/Library/Caches/*).
        let userCaches = home.appendingPathComponent("Library/Caches", isDirectory: true)
        for child in directoryChildren(of: userCaches) {
            try Task.checkCancellation()
            enqueue(
                url: child,
                displayName: Self.friendlyName(for: child.lastPathComponent),
                reason: "Application cache. Regenerated by the app as needed."
            )
        }

        // 3. Hierarchy 4: Sandboxed app containers (~/Library/Containers/*).
        // Only inspect Data/Library/Caches, Data/tmp, and Data/Library/Logs;
        // Documents and Application Support are never candidates.
        let containers = home.appendingPathComponent("Library/Containers", isDirectory: true)
        for child in directoryChildren(of: containers) {
            try Task.checkCancellation()
            let appName = Self.friendlyName(for: child.lastPathComponent)
            enqueue(
                url: child.appendingPathComponent("Data/Library/Caches", isDirectory: true),
                displayName: "\(appName) (sandbox cache)",
                reason: "Sandboxed application cache. Regenerated by the app as needed."
            )
            enqueue(
                url: child.appendingPathComponent("Data/tmp", isDirectory: true),
                displayName: "\(appName) (sandbox temp)",
                reason: "Sandboxed application temporary files. Recreated as needed."
            )
            enqueue(
                url: child.appendingPathComponent("Data/Library/Logs", isDirectory: true),
                displayName: "\(appName) (sandbox logs)",
                reason: "Sandboxed application diagnostic logs."
            )
        }

        // 4. Hierarchy 5: Shared Group Container caches (~/Library/Group Containers/*).
        // Never touch the group container root; only target explicit Caches subdirectories.
        let groupContainers = home.appendingPathComponent("Library/Group Containers", isDirectory: true)
        for child in directoryChildren(of: groupContainers) {
            try Task.checkCancellation()
            let groupName = Self.friendlyName(for: child.lastPathComponent)
            enqueue(
                url: child.appendingPathComponent("Library/Caches", isDirectory: true),
                displayName: "\(groupName) (group cache)",
                reason: "Shared app group cache. Regenerated by the owning apps as needed."
            )
            enqueue(
                url: child.appendingPathComponent("Caches", isDirectory: true),
                displayName: "\(groupName) (group cache)",
                reason: "Shared app group cache. Regenerated by the owning apps as needed."
            )
        }

        // 5. macOS Framework Caches in ~/Library:
        //    - HTTPStorages/<BundleID>/fsCachedData (raw URLCache disk blobs; leaves cookies sqlite alone)
        //    - WebKit/<BundleID>/WebsiteData/{NetworkCache,CacheStorage}
        //    - Saved Application State/<BundleID>.savedState
        let httpStorages = home.appendingPathComponent("Library/HTTPStorages", isDirectory: true)
        for child in directoryChildren(of: httpStorages) {
            try Task.checkCancellation()
            let appName = Self.friendlyName(for: child.lastPathComponent)
            enqueue(
                url: child.appendingPathComponent("fsCachedData", isDirectory: true),
                displayName: "\(appName) (HTTP disk cache)",
                reason: "URLSession disk response cache. Leaves cookies and session credentials untouched."
            )
        }

        let webKitRoot = home.appendingPathComponent("Library/WebKit", isDirectory: true)
        for child in directoryChildren(of: webKitRoot) {
            try Task.checkCancellation()
            let appName = Self.friendlyName(for: child.lastPathComponent)
            enqueue(
                url: child.appendingPathComponent("WebsiteData/NetworkCache", isDirectory: true),
                displayName: "\(appName) (WebKit network cache)",
                reason: "Embedded WebKit network disk cache. Regenerated automatically."
            )
            enqueue(
                url: child.appendingPathComponent("WebsiteData/CacheStorage", isDirectory: true),
                displayName: "\(appName) (WebKit service worker cache)",
                reason: "Embedded WebKit CacheStorage data. Regenerated automatically."
            )
        }

        let savedStateRoot = home.appendingPathComponent("Library/Saved Application State", isDirectory: true)
        for child in directoryChildren(of: savedStateRoot) where child.pathExtension == "savedState" {
            try Task.checkCancellation()
            let bundleID = child.deletingPathExtension().lastPathComponent
            let appName = Self.friendlyName(for: bundleID)
            enqueue(
                url: child,
                displayName: "\(appName) (saved window state)",
                reason: "macOS window restoration snapshot. Recreated when the app next runs."
            )
        }

        // 6. User Logs & Crash Reports (~/Library/Logs/* and ~/Library/DiagnosticReports).
        let logsRoot = home.appendingPathComponent("Library/Logs", isDirectory: true)
        for child in directoryChildren(of: logsRoot) {
            try Task.checkCancellation()
            let name = Self.friendlyName(for: child.lastPathComponent)
            enqueue(
                url: child,
                displayName: "\(name) logs",
                reason: "Application and diagnostic log files."
            )
        }
        enqueue(
            url: home.appendingPathComponent("Library/DiagnosticReports", isDirectory: true),
            displayName: "macOS Crash & Diagnostic Reports",
            reason: "Crash and spin diagnostic reports (.ips / .crash)."
        )

        // 7. Electron / Chromium Sub-Caches inside ~/Library/Application Support/<App>/.
        // Only target strictly regenerable Chromium/Electron cache subfolders; never touch
        // Local Storage, IndexedDB, Cookies, Preferences, or Session Storage.
        let appSupport = home.appendingPathComponent("Library/Application Support", isDirectory: true)
        for appDir in directoryChildren(of: appSupport) {
            try Task.checkCancellation()
            let appName = Self.friendlyName(for: appDir.lastPathComponent)
            for subpath in Self.electronRegenerableSubpaths {
                enqueue(
                    url: appDir.appendingPathComponent(subpath.relativePath, isDirectory: true),
                    displayName: "\(appName) (\(subpath.label))",
                    reason: "Regenerable \(subpath.label) inside Application Support. Login sessions and app settings are kept."
                )
            }
        }

        // 8. Creative, Media & Gaming App Caches (Adobe, Spotify, Steam).
        for mediaCache in Self.creativeAndMediaCaches {
            try Task.checkCancellation()
            enqueue(
                url: home.appendingPathComponent(mediaCache.path, isDirectory: true),
                displayName: mediaCache.name,
                reason: mediaCache.reason
            )
        }

        // 9. Global Developer & Package Manager Caches outside ~/Library/Caches.
        for tool in Self.devToolCaches {
            try Task.checkCancellation()
            enqueue(
                url: home.appendingPathComponent(tool.path, isDirectory: true),
                displayName: tool.name,
                reason: "Developer tool download cache. Repopulated on demand."
            )
        }

        // 10. Optional Darwin Per-User Cache Directory (/private/var/folders/.../C).
        if let darwinCache = darwinUserCacheDirectory {
            for entry in Self.darwinSafeSubcaches {
                try Task.checkCancellation()
                enqueue(
                    url: darwinCache.appendingPathComponent(entry.subpath, isDirectory: true),
                    displayName: entry.name,
                    reason: entry.reason
                )
            }
        }

        // Batch measure all pending directories with `/usr/bin/du -x -sk` (falling back to FileManager).
        let batchSizes = BatchDiskUsageMeasurer.allocatedBytes(
            for: pending.map(\.url),
            fileManager: fileManager
        )

        var candidates: [CacheCandidate] = []
        for item in pending {
            try Task.checkCancellation()
            let canonical = item.url.standardizedFileURL.path
            let size = batchSizes[canonical] ?? BatchDiskUsageMeasurer.fallbackAllocatedSize(at: item.url, fileManager: fileManager)
            guard size >= minimumSize else { continue }
            let lastModified = try? item.url.resourceValues(forKeys: [.contentModificationDateKey]).contentModificationDate
            candidates.append(CacheCandidate(
                url: item.url,
                displayName: item.displayName,
                sizeBytes: size,
                lastModified: lastModified,
                reason: item.reason,
                confidence: item.confidence
            ))
        }

        // 11. Per-Project Build Folders inside approved scanRoots.
        if !scanRoots.isEmpty {
            let projectCandidates = try ProjectBuildScanner().scan(
                roots: scanRoots,
                minimumSize: minimumSize,
                fileManager: fileManager
            )
            for buildCandidate in projectCandidates {
                let canonical = buildCandidate.url.standardizedFileURL.path
                guard seenCanonicalPaths.insert(canonical).inserted else { continue }
                candidates.append(CacheCandidate(
                    url: buildCandidate.url,
                    displayName: buildCandidate.displayName,
                    sizeBytes: buildCandidate.sizeBytes,
                    lastModified: buildCandidate.lastModified,
                    reason: buildCandidate.classification.reason,
                    confidence: buildCandidate.classification.confidence
                ))
            }
        }

        return candidates.sorted { $0.sizeBytes > $1.sizeBytes }
    }

    private func directoryChildren(of parent: URL) -> [URL] {
        guard isEligibleCacheDirectory(parent),
              let children = try? fileManager.contentsOfDirectory(
                  at: parent,
                  includingPropertiesForKeys: [.isDirectoryKey, .isSymbolicLinkKey],
                  options: [.skipsHiddenFiles]
              ) else {
            return []
        }
        return children.filter { isEligibleCacheDirectory($0) }
    }

    private func isEligibleCacheDirectory(_ url: URL) -> Bool {
        guard (try? fileManager.attributesOfItem(atPath: url.path)[.type] as? FileAttributeType) != .typeSymbolicLink else {
            return false
        }
        guard url.resolvingSymlinksInPath().standardizedFileURL.path == url.standardizedFileURL.path else {
            return false
        }
        var isDirectory: ObjCBool = false
        return fileManager.fileExists(atPath: url.path, isDirectory: &isDirectory) && isDirectory.boolValue
    }

